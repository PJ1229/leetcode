#!/usr/bin/env python3
"""Write the public progress page at docs/index.html.

The page is generated from problems.yaml and the solution folders, same as
the README. GitHub Actions republishes it on push.

    python3 dashboard.py
    python3 dashboard.py --check
"""

from __future__ import annotations

import os
import subprocess
import sys
from datetime import date

import nc150

PAGE_PATH = nc150.ROOT / "docs" / "index.html"
LINK_BRANCH = "main"
RECENT_LIMIT = 8


def main(argv: list[str]) -> int:
    check = "--check" in argv
    extra = [arg for arg in argv[1:] if arg != "--check"]
    if extra:
        print("usage: python3 dashboard.py [--check]", file=sys.stderr)
        return 2
    try:
        text = build_page(date.today())
    except (OSError, nc150.ListError) as exc:
        print(exc, file=sys.stderr)
        return 1

    if check:
        current = PAGE_PATH.read_text(encoding="utf-8") if PAGE_PATH.exists() else ""
        if current != text:
            print("docs/index.html is out of date. Run: python3 dashboard.py", file=sys.stderr)
            return 1
        print("docs/index.html is current")
        return 0

    PAGE_PATH.parent.mkdir(parents=True, exist_ok=True)
    PAGE_PATH.write_text(text, encoding="utf-8", newline="\n")
    print("wrote docs/index.html")
    return 0


def build_page(today: date) -> str:
    problems = nc150.load_problems()
    return render(problems, today, github_repo_url())


def render(problems: list[dict], today: date, repo_url: str, has_code=None) -> str:
    if has_code is None:
        has_code = nc150.has_solution
    repo_url = repo_url.rstrip("/")
    total = len(problems)
    solved = sum(problem["status"] == "solved" for problem in problems)
    review = sum(problem["status"] == "review" for problem in problems)
    todo = total - solved - review
    done = solved + review
    dated = [
        problem
        for problem in problems
        if problem["status"] in nc150.DONE and problem["solved_date"] is not None
    ]
    current, longest, latest = nc150.streak_stats(
        [problem["solved_date"] for problem in dated], today
    )
    percent = round(100 * done / total) if total else 0
    page = pages_url(repo_url)
    title = f"NeetCode 150 · {done}/{total}"
    description = (
        f"C++ interview practice. {done} of {total} done, "
        f"current streak {day_word(current)}."
    )
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{esc(title)}</title>",
        f'<meta name="description" content="{esc(description)}">',
        f'<link rel="canonical" href="{esc(page)}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(description)}">',
        f'<meta property="og:url" content="{esc(page)}">',
        "<style>",
        CSS,
        "</style>",
        "</head>",
        "<body>",
        "<!-- Generated by dashboard.py from problems.yaml and the solution folders. -->",
        "<main>",
        header_block(),
        hero_block(done, total, percent, solved, review, todo),
        topics_block(problems),
        difficulty_block(problems),
        streak_block(current, longest, latest),
        recent_block(problems, dated, repo_url, has_code),
        solutions_block(problems, repo_url, has_code),
        footer_block(repo_url),
        "</main>",
        "</body>",
        "</html>",
        "",
    ]
    return "\n".join(parts)


def header_block() -> str:
    return "\n".join(
        [
            "<header>",
            '<p class="eyebrow">C++ interview practice</p>',
            "<h1>NeetCode 150</h1>",
            '<p class="lede">Problems solved from scratch, in roadmap order. '
            "Solved and review both count as done.</p>",
            "</header>",
        ]
    )


def hero_block(done: int, total: int, percent: int, solved: int, review: int, todo: int) -> str:
    return "\n".join(
        [
            '<section class="hero" aria-label="Overall progress">',
            '<p class="score"><span class="num">'
            f"{done}</span><span class=\"den\">/ {total}</span></p>",
            f'<p class="percent">{percent}%</p>',
            '<div class="track" role="progressbar" '
            f'aria-valuenow="{done}" aria-valuemin="0" aria-valuemax="{total}" '
            'aria-label="Problems done">',
            f'<span style="width:{bar_width(done, total)}"></span>',
            "</div>",
            "<ul>",
            f"<li><strong>{solved}</strong> solved</li>",
            f"<li><strong>{review}</strong> in review</li>",
            f"<li><strong>{todo}</strong> to do</li>",
            "</ul>",
            "</section>",
        ]
    )


def topics_block(problems: list[dict]) -> str:
    rows = []
    for topic in nc150.TOPICS:
        items = [problem for problem in problems if problem["topic"] == topic.id]
        done = sum(problem["status"] in nc150.DONE for problem in items)
        label = f"{topic.directory[:2]} · {topic.name}"
        rows.append(
            "\n".join(
                [
                    "<li>",
                    "<div class=\"topic-line\">",
                    f"<span>{esc(label)}</span>",
                    f"<span class=\"count\">{done}/{len(items)}</span>",
                    "</div>",
                    '<div class="track" role="progressbar" '
                    f'aria-valuenow="{done}" aria-valuemin="0" aria-valuemax="{len(items)}" '
                    f'aria-label="{esc(topic.name)}">',
                    f'<span style="width:{bar_width(done, len(items))}"></span>',
                    "</div>",
                    "</li>",
                ]
            )
        )
    return "\n".join(
        [
            "<section>",
            "<h2>Topics</h2>",
            '<ol class="topics">',
            "\n".join(rows),
            "</ol>",
            "</section>",
        ]
    )


def difficulty_block(problems: list[dict]) -> str:
    cards = []
    for level in nc150.DIFFICULTIES:
        items = [problem for problem in problems if problem["difficulty"] == level]
        done = sum(problem["status"] in nc150.DONE for problem in items)
        cards.append(
            "\n".join(
                [
                    f'<article class="{level.lower()}">',
                    f"<h3>{esc(level)}</h3>",
                    f"<p>{done}<span> / {len(items)}</span></p>",
                    "</article>",
                ]
            )
        )
    return "\n".join(
        [
            "<section>",
            "<h2>Difficulty</h2>",
            '<div class="diffs">',
            "\n".join(cards),
            "</div>",
            "</section>",
        ]
    )


def streak_block(current: int, longest: int, latest: date | None) -> str:
    if latest is None:
        note = "No solved dates yet."
    elif current == 0:
        note = f"Last solve {format_date(latest)}. Longest streak was {day_word(longest)}."
    else:
        note = f"Longest streak is {day_word(longest)}."
    return "\n".join(
        [
            "<section>",
            "<h2>Streak</h2>",
            f'<p class="streak">{esc(day_word(current))}</p>',
            f'<p class="note">{esc(note)}</p>',
            "</section>",
        ]
    )


def recent_block(problems: list[dict], dated: list[dict], repo_url: str, has_code) -> str:
    lines = ["<section>", "<h2>Recent solves</h2>"]
    if not dated:
        lines.append('<p class="note">No solves yet.</p>')
        lines.append("</section>")
        return "\n".join(lines)
    order = {id(problem): index for index, problem in enumerate(problems)}
    pool = sorted(dated, key=lambda problem: order[id(problem)])
    pool.sort(key=lambda problem: problem["solved_date"], reverse=True)
    items = []
    for problem in pool[:RECENT_LIMIT]:
        href, kind = code_link(problem, repo_url, has_code)
        level = problem["difficulty"]
        status = problem["status"]
        meta = (
            f"{esc(nc150.TOPIC_BY_ID[problem['topic']].name)}"
            f' · <span class="diff {level.lower()}">{esc(level)}</span>'
            f' · <span class="status {status}">{esc(status)}</span>'
        )
        if kind == "folder":
            meta += " · code"
        items.append(
            "\n".join(
                [
                    "<li>",
                    f'<time datetime="{problem["solved_date"].isoformat()}">'
                    f"{esc(format_date(problem['solved_date']))}</time>",
                    f'<a href="{esc(href)}">{esc(problem["title"])}</a>',
                    f'<p class="meta">{meta}</p>',
                    "</li>",
                ]
            )
        )
    lines.append('<ol class="recent">')
    lines.append("\n".join(items))
    lines.append("</ol>")
    lines.append("</section>")
    return "\n".join(lines)


def solutions_block(problems: list[dict], repo_url: str, has_code) -> str:
    lines = ["<section>", "<h2>Solutions</h2>"]
    groups = []
    for topic in nc150.TOPICS:
        items = [
            problem
            for problem in problems
            if problem["topic"] == topic.id and has_code(problem)
        ]
        if not items:
            continue
        entries = []
        for problem in items:
            href = folder_url(repo_url, problem)
            entries.append(
                f'<li><a href="{esc(href)}">{problem["number"]}. {esc(problem["title"])}</a></li>'
            )
        groups.append(
            "\n".join(
                [
                    f"<h3>{esc(topic.name)}</h3>",
                    '<ul class="codes">',
                    "\n".join(entries),
                    "</ul>",
                ]
            )
        )
    if not groups:
        lines.append('<p class="note">No solution folders yet.</p>')
    else:
        lines.append("\n".join(groups))
    lines.append("</section>")
    return "\n".join(lines)


def footer_block(repo_url: str) -> str:
    return "\n".join(
        [
            "<footer>",
            f'<a href="{esc(repo_url)}">Repository</a>',
            '<a href="https://neetcode.io/practice">NeetCode 150</a>',
            "</footer>",
        ]
    )


def code_link(problem: dict, repo_url: str, has_code) -> tuple[str, str]:
    if has_code(problem):
        return folder_url(repo_url, problem), "folder"
    return problem["url"], "statement"


def folder_url(repo_url: str, problem: dict) -> str:
    rel = nc150.problem_dir(problem).relative_to(nc150.ROOT).as_posix()
    return f"{repo_url}/tree/{LINK_BRANCH}/{rel}"


def bar_width(done: int, total: int) -> str:
    if done <= 0 or total <= 0:
        return "0%"
    if done >= total:
        return "100%"
    percent = max(done * 100 / total, 1.25)
    return f"{percent:.2f}%"


def day_word(count: int) -> str:
    return "1 day" if count == 1 else f"{count} days"


def format_date(value: date) -> str:
    return f"{value.strftime('%b')} {value.day}, {value.year}"


def pages_url(repo_url: str) -> str:
    parts = repo_url.rstrip("/").split("/")
    owner, repo = parts[-2], parts[-1]
    if repo.lower() == f"{owner.lower()}.github.io":
        return f"https://{owner.lower()}.github.io/"
    return f"https://{owner.lower()}.github.io/{repo}/"


def github_repo_url() -> str:
    override = os.environ.get("DASHBOARD_REPO_URL", "").strip()
    if override:
        return _clean_remote(override)
    env_repo = os.environ.get("GITHUB_REPOSITORY", "").strip()
    server = os.environ.get("GITHUB_SERVER_URL", "https://github.com").rstrip("/")
    if env_repo and "/" in env_repo and "://" not in env_repo and "@" not in env_repo:
        return f"{server}/{env_repo}"
    try:
        raw = subprocess.check_output(
            ["git", "remote", "get-url", "origin"],
            cwd=nc150.ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        raise nc150.ListError("cannot read origin remote") from exc
    return _clean_remote(raw)


def _clean_remote(raw: str) -> str:
    text = raw.strip().removesuffix(".git")
    if text.startswith("git@"):
        host, path = text[4:].split(":", 1)
        return f"https://{host}/{path}".rstrip("/")
    if "://" in text:
        scheme, rest = text.split("://", 1)
        if "@" in rest:
            rest = rest.split("@", 1)[1]
        return f"{scheme}://{rest}".rstrip("/")
    raise nc150.ListError("cannot parse origin remote")


def esc(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )



#!/usr/bin/env python3
"""Regenerate README.md from problems.yaml, intro.md, and the solution folders.

    python3 readme.py
    python3 readme.py --check
"""

from __future__ import annotations

import sys
from datetime import date

import nc150

README_PATH = nc150.ROOT / "README.md"
INTRO_PATH = nc150.ROOT / "intro.md"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    extra = [arg for arg in argv[1:] if arg != "--check"]
    if extra:
        print("usage: python3 readme.py [--check]", file=sys.stderr)
        return 2
    try:
        text = build_readme(date.today())
    except (OSError, nc150.ListError) as exc:
        print(exc, file=sys.stderr)
        return 1

    if check:
        current = README_PATH.read_text(encoding="utf-8") if README_PATH.exists() else ""
        if current != text:
            print("README.md is out of date. Run: python3 readme.py", file=sys.stderr)
            return 1
        print("README.md is current")
        return 0

    README_PATH.write_text(text, encoding="utf-8", newline="\n")
    print("wrote README.md")
    return 0


def build_readme(today: date) -> str:
    problems = nc150.load_problems()
    if not INTRO_PATH.is_file():
        raise nc150.ListError("intro.md is missing")
    intro = INTRO_PATH.read_text(encoding="utf-8").rstrip()
    generated = render(problems, today)
    return intro + "\n\n---\n\n" + generated


def render(problems: list[dict], today: date) -> str:
    sections = [
        "<!-- Generated by readme.py from problems.yaml and the solution folders.\n"
        "     Edit intro.md for the introduction. Edit problems.yaml for progress. -->",
        progress_section(problems),
        topic_section(problems),
        difficulty_section(problems),
        streak_section(problems, today),
    ]
    started = in_progress_section(problems)
    if started:
        sections.append(started)
    sections.append(solved_section(problems))
    sections.append(roadmap_section(problems))
    stray = stray_section(problems)
    if stray:
        sections.append(stray)
    return "\n\n".join(sections).rstrip() + "\n"


def progress_section(problems: list[dict]) -> str:
    total = len(problems)
    solved = sum(problem["status"] == "solved" for problem in problems)
    review = sum(problem["status"] == "review" for problem in problems)
    todo = sum(problem["status"] == "todo" for problem in problems)
    done = solved + review
    files = sum(nc150.has_solution(problem) for problem in problems)
    percent = round(100 * done / total) if total else 0
    bar = nc150.progress_bar(done, total)
    file_word = "file" if files == 1 else "files"
    return "\n".join(
        [
            "## Progress",
            "",
            f"**{done} / {total}** done ({percent}%). Done means `solved` or `review`.",
            "",
            f"`{bar}`",
            "",
            f"{solved} solved · {review} in review · {todo} to do · {files} `solution.cpp` {file_word}",
        ]
    )


def topic_section(problems: list[dict]) -> str:
    rows = []
    for topic in nc150.TOPICS:
        rows.append(topic_row(topic.name, problems_for(problems, topic.id), f"#topic-{topic.id}"))
    rows.append(topic_row("Total", problems, anchor=None, bold=True))
    return "\n".join(
        [
            "## By topic",
            "",
            "Easy, Medium, and Hard are the size of each topic. Solved, review, and to do follow `status`.",
            "",
            table(
                ["Topic", "Easy", "Medium", "Hard", "Solved", "Review", "To do", "Total"],
                rows,
            ),
        ]
    )


def topic_row(name: str, items: list[dict], anchor: str | None, bold: bool = False) -> list[str]:
    diffs = {level: sum(problem["difficulty"] == level for problem in items) for level in nc150.DIFFICULTIES}
    solved = sum(problem["status"] == "solved" for problem in items)
    review = sum(problem["status"] == "review" for problem in items)
    todo = sum(problem["status"] == "todo" for problem in items)
    label = f"[{name}]({anchor})" if anchor else name
    cells = [
        label,
        str(diffs["Easy"]),
        str(diffs["Medium"]),
        str(diffs["Hard"]),
        str(solved),
        str(review),
        str(todo),
        str(len(items)),
    ]
    if bold:
        cells = [f"**{cell}**" for cell in cells]
    return cells


def difficulty_section(problems: list[dict]) -> str:
    rows = []
    for level in nc150.DIFFICULTIES:
        items = [problem for problem in problems if problem["difficulty"] == level]
        rows.append(status_row(level, items))
    rows.append(status_row("Total", problems, bold=True))
    return "\n".join(
        [
            "## By difficulty",
            "",
            table(["Difficulty", "Solved", "Review", "To do", "Total"], rows),
        ]
    )


def status_row(name: str, items: list[dict], bold: bool = False) -> list[str]:
    cells = [
        name,
        str(sum(problem["status"] == "solved" for problem in items)),
        str(sum(problem["status"] == "review" for problem in items)),
        str(sum(problem["status"] == "todo" for problem in items)),
        str(len(items)),
    ]
    if bold:
        cells = [f"**{cell}**" for cell in cells]
    return cells


def streak_section(problems: list[dict], today: date) -> str:
    dated = [
        problem
        for problem in problems
        if problem["status"] in nc150.DONE and problem["solved_date"] is not None
    ]
    undated = [
        problem
        for problem in problems
        if problem["status"] in nc150.DONE and problem["solved_date"] is None
    ]
    current, longest, latest = nc150.streak_stats(
        [problem["solved_date"] for problem in dated], today
    )
    lines = [
        "## Streak",
        "",
        f"Current streak: **{day_word(current)}**. Longest streak: **{day_word(longest)}**.",
    ]
    if latest is not None and current == 0:
        lines.append("")
        lines.append(f"Last solved date: {latest.isoformat()}.")
    lines.extend(["", "### Recent solves", ""])
    if not dated:
        lines.append("No `solved_date` entries yet.")
    else:
        # Stable on a shared date: keep roadmap order within one day.
        order = {id(problem): index for index, problem in enumerate(problems)}
        pool = sorted(dated, key=lambda problem: order[id(problem)])
        pool.sort(key=lambda problem: problem["solved_date"], reverse=True)
        rows = [
            [
                problem["solved_date"].isoformat(),
                problem_link(problem),
                nc150.TOPIC_BY_ID[problem["topic"]].name,
                problem["difficulty"],
                problem["status"],
                folder_link(problem),
            ]
            for problem in pool[:10]
        ]
        lines.append(table(["Date", "Problem", "Topic", "Difficulty", "Status", "Folder"], rows))
    if undated:
        lines.append("")
        lines.append(
            f"{len(undated)} finished {'problem has' if len(undated) == 1 else 'problems have'} "
            "no `solved_date`, so they stay out of the streak."
        )
    return "\n".join(lines)


def in_progress_section(problems: list[dict]) -> str:
    started = [
        problem
        for problem in problems
        if problem["status"] == "todo" and nc150.has_solution(problem)
    ]
    if not started:
        return ""
    rows = [
        [
            str(problem["number"]),
            problem_link(problem),
            nc150.TOPIC_BY_ID[problem["topic"]].name,
            folder_link(problem),
        ]
        for problem in started
    ]
    return "\n".join(
        [
            "## In progress",
            "",
            "These are still `todo`, and the folder is already in the repo.",
            "",
            table(["#", "Problem", "Topic", "Folder"], rows),
        ]
    )


def solved_section(problems: list[dict]) -> str:
    finished = [problem for problem in problems if problem["status"] in nc150.DONE]
    lines = [
        "## Solved",
        "",
        "Every `solved` and `review` problem. The folder link points at the code in this repo.",
        "",
    ]
    if not finished:
        first = problems[0]
        lines.append(f"None yet. Start with `python3 new.py {first['number']}` ({first['title']}).")
        return "\n".join(lines)
    rows = []
    for problem in finished:
        solved = problem["solved_date"].isoformat() if problem["solved_date"] else "—"
        rows.append(
            [
                str(problem["number"]),
                problem_link(problem),
                nc150.TOPIC_BY_ID[problem["topic"]].name,
                problem["difficulty"],
                problem["status"],
                solved,
                folder_link(problem),
            ]
        )
    lines.append(
        table(["#", "Problem", "Topic", "Difficulty", "Status", "Solved", "Folder"], rows)
    )
    return "\n".join(lines)


def roadmap_section(problems: list[dict]) -> str:
    lines = [
        "## Roadmap",
        "",
        "NeetCode 150 in roadmap order. Premium marks a LeetCode paywall. The same statement is free on NeetCode.",
        "",
    ]
    chunks = []
    for topic in nc150.TOPICS:
        items = problems_for(problems, topic.id)
        done = sum(problem["status"] in nc150.DONE for problem in items)
        rows = []
        for problem in items:
            rows.append(
                [
                    str(problem["number"]),
                    problem_link(problem),
                    problem["difficulty"],
                    problem["status"],
                    folder_link(problem),
                ]
            )
        chunks.append(
            "\n".join(
                [
                    f'<a id="topic-{topic.id}"></a>',
                    "",
                    f"### {topic.name} ({done}/{len(items)})",
                    "",
                    table(["#", "Problem", "Difficulty", "Status", "Folder"], rows),
                ]
            )
        )
    lines.append("\n\n".join(chunks))
    return "\n".join(lines)


def stray_section(problems: list[dict]) -> str:
    paths = nc150.stray_solution_files(problems)
    if not paths:
        return ""
    lines = [
        "## Outside the roadmap",
        "",
        "These `solution.cpp` files are outside a NeetCode 150 folder. CI still compiles and runs them.",
        "",
    ]
    for path in paths:
        rel = path.relative_to(nc150.ROOT).as_posix()
        lines.append(f"- [`{rel}`]({rel})")
    return "\n".join(lines)


def problems_for(problems: list[dict], topic_id: str) -> list[dict]:
    return [problem for problem in problems if problem["topic"] == topic_id]


def problem_link(problem: dict) -> str:
    title = problem["title"].replace("|", "\\|")
    link = f"[{title}]({problem['url']})"
    if problem["premium"]:
        link += " · premium"
    return link


def folder_link(problem: dict) -> str:
    if not nc150.has_solution(problem):
        return "—"
    rel = nc150.problem_dir(problem).relative_to(nc150.ROOT).as_posix()
    return f"[folder]({rel})"


def table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def day_word(count: int) -> str:
    return "1 day" if count == 1 else f"{count} days"


if __name__ == "__main__":
    sys.exit(main(sys.argv))
